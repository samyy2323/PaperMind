"""Bundle the correction-training stage scripts into ONE self-contained file (works pasted into any notebook cell).

    python backend/training/bundle.py      ->  backend/training/papermind_byt5_all_in_one.py
"""
import re
from pathlib import Path

SRC = Path(__file__).resolve().parent / "correction"
OUT = Path(__file__).resolve().parent / "papermind_byt5_all_in_one.py"

MODULES = [("pm_common", "common"), ("pm_noise", "noise"), ("evaluate_correction", "eval"), ("build_dataset", "build"),
           ("train", "train")]
LOCAL = r"(?:pm_common|pm_noise|evaluate_correction)"


def clean(text: str, tag: str) -> str:
    text = text.replace("from __future__ import annotations\n", "")
    text = re.sub(rf"^from {LOCAL} import \((?:.|\n)*?\)[^\n]*\n", "", text, flags=re.M)  # multi-line import
    text = re.sub(rf"^from {LOCAL} import [^\n(]*\n", "", text, flags=re.M)
    text = re.sub(r"^sys\.path\.insert\(0, [^\n]*\n", "", text, flags=re.M)
    text = text.replace("HERE = Path(__file__).resolve().parent\n", "")
    text = text.replace('[s for s in (HERE / "seed_sentences.txt").read_text(encoding="utf-8").splitlines() if s.strip()]',
                        "list(SEED_SENTENCES)")
    text = re.sub(r"\nif __name__ == \"__main__\":\n    raise SystemExit\(main\(\)\)\n?", "\n", text)
    return text.replace("def main(", f"def _main_{tag}(")


def build() -> str:
    seeds = [s for s in (SRC / "seed_sentences.txt").read_text(encoding="utf-8").splitlines() if s.strip()]
    parts = [
        '"""PaperMind - ByT5 OCR-correction: data builder + trainer + evaluator in ONE file (auto-generated by bundle.py).\n\n'
        "    python papermind_byt5_all_in_one.py --preset base --out /content/run1 [--iam-dir ...] [--manifest ...]\n"
        "    # in a notebook:   main(['--preset', 'smoke', '--out', '/content/run1'])\n"
        'Presets: smoke (5 min check) | small | base (A100, recommended) | large (A100 40GB, slowest, strongest).\n"""\n'
        "from __future__ import annotations\n",
        "SEED_SENTENCES = " + repr(seeds) + "\n",
    ]
    for module, tag in MODULES:
        parts.append(f"\n# {'=' * 100}\n# {module}\n# {'=' * 100}\n" + clean((SRC / f"{module}.py").read_text(encoding="utf-8"), tag))
    parts.append("\n" + (SRC / "tail_main.py").read_text(encoding="utf-8"))
    return "".join(parts)


if __name__ == "__main__":
    code = build()
    compile(code, str(OUT), "exec")  # fail loudly on a bad bundle
    OUT.write_text(code, encoding="utf-8")
    print(f"wrote {OUT} ({len(code.splitlines())} lines)")
